def sign_file(path: Path) -> bool:
    """
    Authenticode-sign `path` when signing is configured; otherwise report and continue.

    Configure with environment variables (never put the password on a command line or in a file):
      STUDIO_SIGN_PFX       path to the .pfx code-signing certificate
      STUDIO_SIGN_PASSWORD  its password
      STUDIO_SIGNTOOL       path to signtool.exe (default: 'signtool' on PATH)
      STUDIO_SIGN_TIMESTAMP RFC 3161 timestamp URL (default: http://timestamp.digicert.com)
    """
    pfx = os.environ.get("STUDIO_SIGN_PFX")
    if not pfx:
        print(f"    [signing] skipped for {path.name} (STUDIO_SIGN_PFX not set; binary will be unsigned)")
        return False
    cmd = [
        os.environ.get("STUDIO_SIGNTOOL", "signtool"), "sign",
        "/f", pfx, "/fd", "sha256",
        "/tr", os.environ.get("STUDIO_SIGN_TIMESTAMP", "http://timestamp.digicert.com"), "/td", "sha256",
    ]
    if os.environ.get("STUDIO_SIGN_PASSWORD"):
        cmd += ["/p", os.environ["STUDIO_SIGN_PASSWORD"]]
    cmd.append(str(path))
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        # signtool echoes the command on failure; never print it (it would contain the password)
        print(f"    [signing] FAILED for {path.name} (signtool exit {proc.returncode})")
        return False
    print(f"    [signing] signed {path.name}")
    return True
